-- QD REV-01 foundation. Order eligibility remains TD-owned, not inferred here.
ALTER TABLE uteexpress.order_items ADD CONSTRAINT uq_review_order_item_facts UNIQUE (id, order_id, product_id);
CREATE TABLE uteexpress.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL UNIQUE,
    order_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES uteexpress.users(id),
    product_id BIGINT NOT NULL REFERENCES uteexpress.products(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(2000) NOT NULL CHECK (char_length(comment) BETWEEN 50 AND 2000 AND comment ~ '[^[:space:]]'),
    visibility VARCHAR(16) NOT NULL DEFAULT 'PUBLIC' CHECK (visibility IN ('PUBLIC','HIDDEN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_review_item_facts FOREIGN KEY (order_item_id,order_id,product_id)
        REFERENCES uteexpress.order_items(id,order_id,product_id),
    CONSTRAINT fk_review_buyer FOREIGN KEY (order_id,user_id) REFERENCES uteexpress.orders(id,buyer_id)
);
CREATE INDEX ix_reviews_product_visibility ON uteexpress.reviews(product_id,visibility,created_at DESC,id DESC);
CREATE TABLE uteexpress.review_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES uteexpress.reviews(id),
    media_type VARCHAR(32) NOT NULL CHECK (media_type IN ('image/jpeg','image/png','image/webp')),
    storage_key VARCHAR(255) NOT NULL UNIQUE CHECK (
        storage_key ~ '^reviews/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$'),
    position INTEGER NOT NULL CHECK (position BETWEEN 0 AND 2),
    UNIQUE (review_id,position)
);
