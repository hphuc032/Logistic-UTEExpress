-- INT-02: new immutable Ops physical-receipt evidence; no historical backfill or applied migration edit.
CREATE TABLE uteexpress.shipment_return_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    received_by BIGINT NOT NULL,
    original_order_version BIGINT NOT NULL,
    original_shipment_version BIGINT NOT NULL,
    receipt_reference VARCHAR(255) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_shipment_return_receipts_shipment UNIQUE (shipment_id),
    CONSTRAINT uq_shipment_return_receipts_order UNIQUE (order_id),
    CONSTRAINT fk_shipment_return_receipts_order FOREIGN KEY (order_id) REFERENCES uteexpress.orders(id),
    CONSTRAINT fk_shipment_return_receipts_shipment FOREIGN KEY (shipment_id) REFERENCES uteexpress.shipments(id),
    CONSTRAINT fk_shipment_return_receipts_actor FOREIGN KEY (received_by) REFERENCES uteexpress.users(id),
    CONSTRAINT ck_shipment_return_receipts_versions CHECK (original_order_version >= 0 AND original_shipment_version >= 0),
    CONSTRAINT ck_shipment_return_receipts_reference CHECK (receipt_reference = btrim(receipt_reference) AND receipt_reference ~ '[^[:space:]]'),
    CONSTRAINT ck_shipment_return_receipts_time CHECK (isfinite(received_at))
);
-- Prevent mismatched Order/Shipment evidence, including writes outside JPA.
ALTER TABLE uteexpress.shipments ADD CONSTRAINT uq_shipments_id_order UNIQUE (id, order_id);
ALTER TABLE uteexpress.shipment_return_receipts ADD CONSTRAINT fk_shipment_return_receipts_parent
    FOREIGN KEY (shipment_id, order_id) REFERENCES uteexpress.shipments(id, order_id);
CREATE FUNCTION uteexpress.preserve_shipment_return_receipt() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Return receipt evidence is append-only' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER tr_preserve_shipment_return_receipt
    BEFORE UPDATE OR DELETE OR TRUNCATE ON uteexpress.shipment_return_receipts
    FOR EACH STATEMENT EXECUTE FUNCTION uteexpress.preserve_shipment_return_receipt();
