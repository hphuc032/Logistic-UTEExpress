CREATE TABLE uteexpress.shipment_delivery_failures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES uteexpress.shipments(id),
    attempt_number INTEGER NOT NULL CHECK (attempt_number IN (1, 2)),
    source_shipment_version BIGINT NOT NULL CHECK (source_shipment_version >= 0),
    shipper_id BIGINT NOT NULL REFERENCES uteexpress.users(id),
    failure_reason VARCHAR(1000) NOT NULL CHECK (failure_reason ~ '[^[:space:]]'),
    evidence_reference VARCHAR(255) NOT NULL CHECK (evidence_reference ~ '[^[:space:]]'),
    recorded_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_delivery_failure_attempt UNIQUE (shipment_id, attempt_number),
    CONSTRAINT uq_delivery_failure_version UNIQUE (shipment_id, source_shipment_version)
);

CREATE FUNCTION uteexpress.preserve_delivery_failure() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Delivery failure evidence is append-only' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER tr_preserve_delivery_failure
    BEFORE UPDATE OR DELETE ON uteexpress.shipment_delivery_failures
    FOR EACH ROW EXECUTE FUNCTION uteexpress.preserve_delivery_failure();
