-- RETURN-01 Phase 1. QD must approve timestamp/order, added version and evidence checks before merge.
CREATE TABLE uteexpress.return_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id BIGINT NOT NULL,
    requested_by BIGINT NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(16) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    decided_by BIGINT,
    decision_at TIMESTAMPTZ,
    decision_note VARCHAR(1000),
    received_at TIMESTAMPTZ,
    restockable BOOLEAN,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_return_requests PRIMARY KEY (id),
    CONSTRAINT uq_return_requests_order_id UNIQUE (order_id),
    CONSTRAINT fk_return_requests_order_id FOREIGN KEY (order_id, requested_by) REFERENCES uteexpress.orders(id, buyer_id),
    CONSTRAINT fk_return_requests_requested_by FOREIGN KEY (requested_by) REFERENCES uteexpress.users(id),
    CONSTRAINT fk_return_requests_decided_by FOREIGN KEY (decided_by) REFERENCES uteexpress.users(id),
    CONSTRAINT ck_return_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_return_requests_reason CHECK (reason ~ '[^[:space:]]'),
    CONSTRAINT ck_return_requests_version CHECK (version >= 0),
    CONSTRAINT ck_return_requests_times CHECK (
        created_at = requested_at AND updated_at >= created_at
        AND (decision_at IS NULL OR (decision_at >= requested_at AND updated_at = decision_at))),
    CONSTRAINT ck_return_requests_decision CHECK (
        (status = 'PENDING' AND decided_by IS NULL AND decision_at IS NULL AND decision_note IS NULL
            AND updated_at = requested_at)
        OR (status = 'APPROVED' AND decided_by IS NOT NULL AND decision_at IS NOT NULL AND decision_note IS NULL)
        OR (status = 'REJECTED' AND decided_by IS NOT NULL AND decision_at IS NOT NULL
            AND decision_note IS NOT NULL AND decision_note ~ '[^[:space:]]')),
    -- Unknown receipt/restockability must remain NULL. Later owner-approved contracts need a new migration.
    CONSTRAINT ck_return_requests_no_receipt CHECK (received_at IS NULL AND restockable IS NULL)
);
