-- Reserved PAY-02 version: receipt -> Shipping evidence -> manual COD refund.
-- No historical backfill; PAID Payment and received ReturnRequest remain unchanged.
ALTER TABLE uteexpress.payments ADD CONSTRAINT uq_payments_id_order UNIQUE (id, order_id);
ALTER TABLE uteexpress.return_requests ADD CONSTRAINT uq_return_requests_id_order UNIQUE (id, order_id);

CREATE TABLE uteexpress.refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES uteexpress.orders(id),
    payment_id BIGINT NOT NULL UNIQUE,
    return_request_id BIGINT NOT NULL UNIQUE,
    processed_by BIGINT NOT NULL REFERENCES uteexpress.users(id),
    operation VARCHAR(64) COLLATE "C" NOT NULL CHECK (operation = 'PAY02_MANUAL_COD_REFUND_V1'),
    idempotency_key VARCHAR(255) COLLATE "C" NOT NULL CHECK (idempotency_key ~ '[^[:space:]]'),
    schema_version INTEGER NOT NULL CHECK (schema_version = 1),
    expected_order_version BIGINT NOT NULL CHECK (expected_order_version >= 0 AND expected_order_version < 9223372036854775807),
    expected_return_request_version BIGINT NOT NULL CHECK (expected_return_request_version >= 0),
    canonical_payload BYTEA NOT NULL CHECK (octet_length(canonical_payload) > 0),
    payload_sha256 BYTEA NOT NULL CHECK (octet_length(payload_sha256) = 32),
    amount NUMERIC(19,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric AND amount = trunc(amount)),
    status VARCHAR(16) NOT NULL CHECK (status = 'SUCCEEDED'),
    proof_reference VARCHAR(255) NOT NULL CHECK (proof_reference ~ '[^[:space:]]'),
    server_timestamp TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    result_order_version BIGINT NOT NULL CHECK (result_order_version = expected_order_version + 1),
    payment_paid_at TIMESTAMPTZ NOT NULL CHECK (payment_paid_at <= server_timestamp),
    return_received_at TIMESTAMPTZ NOT NULL CHECK (return_received_at <= server_timestamp),
    CONSTRAINT uq_refunds_operation_key UNIQUE (operation, idempotency_key),
    CONSTRAINT fk_refunds_payment_order FOREIGN KEY (payment_id, order_id) REFERENCES uteexpress.payments(id, order_id),
    CONSTRAINT fk_refunds_return_order FOREIGN KEY (return_request_id, order_id) REFERENCES uteexpress.return_requests(id, order_id),
    CONSTRAINT ck_refunds_ids CHECK (id > 0 AND order_id > 0 AND payment_id > 0 AND return_request_id > 0 AND processed_by > 0),
    CONSTRAINT ck_refunds_created CHECK (created_at = server_timestamp)
);

CREATE FUNCTION uteexpress.reject_refund_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Successful refund ledger is append-only' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER tr_refunds_no_update_delete BEFORE UPDATE OR DELETE ON uteexpress.refunds
    FOR EACH ROW EXECUTE FUNCTION uteexpress.reject_refund_mutation();
CREATE TRIGGER tr_refunds_no_truncate BEFORE TRUNCATE ON uteexpress.refunds
    FOR EACH STATEMENT EXECUTE FUNCTION uteexpress.reject_refund_mutation();
